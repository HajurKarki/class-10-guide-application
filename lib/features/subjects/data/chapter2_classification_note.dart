**CLASS PISCES (Fish):**

**Basic Features:**
- Cold-blooded (ectothermic) - body temperature matches environment
- Gills for aquatic respiration
- Fins (unpaired: dorsal, anal, caudal; paired: pectoral, pelvic)
- Scales (dermal plates)
- Closed circulatory system with 2-chambered heart
- Most ancient vertebrates (450+ million years)

**Fish Adaptations:**
- Streamlined shape reduces drag
- Mucus layer on scales reduces friction
- Swim bladder (buoyancy control)
- Operculum (gill cover) protects gills
- Lateral line system: senses vibrations and pressure changes

**Sub-classes:**

*Chondrichthyes* (Cartilaginous Fish):
- Skeleton: cartilage, not bone (lighter but less strong)
- Examples: Sharks, rays, skates
- Sharks:
  - Electroreception: sense electrical fields generated by muscle contractions
  - Multiple rows of teeth (replaceable, not fused to jaw)
  - Powerful swimmers, efficient predators
  - Some species (whale shark) filter feeders (plankton)
- Ecological role: apex predators, maintain ecosystem balance

*Osteichthyes* (Bony Fish):
- Skeleton: bone (denser, stronger than cartilage)
- Swim bladder: gas-filled organ for buoyancy
- Operculum: protective gill cover
- Most abundant vertebrates
- Examples: Salmon, tuna, goldfish, cod, trout
- Adaptations:
  - Some have air-breathing chambers (bettas, catfish)
  - Some produce venomous spines (stonefish, lionfish)
  - Some are electric (electric eel generates 600V discharge)

**Ecological Role:**
- Food source: primary protein for 3 billion+ humans
- Ecosystem engineers: nutrient cycling
- Indicator species: bioaccumulate pollutants
- Overfishing: many species declining

