# DEFINITIONS

## Essential Terms

**Taxonomy:** The science of classifying and naming organisms based on evolutionary relationships.

**Classification:** The arrangement of organisms into hierarchical groups based on shared characteristics.

**Binomial Nomenclature:** A naming system using two Latin terms (genus and species) to identify organisms uniquely.

**Genus:** A category in taxonomy containing closely related species that share recent common ancestry.

**Species:** The basic unit of classification; a group of organisms that can interbreed and produce fertile offspring.

**Phylum:** A major division of organisms containing related classes.

**Kingdom:** The broadest category of organisms sharing fundamental characteristics.

**Eukaryotic:** Organisms with cells containing a membrane-bound nucleus and organelles.

**Prokaryotic:** Organisms with cells lacking a membrane-bound nucleus; DNA in nucleoid region.

**Autotrophic:** Organisms that produce their own food (like plants through photosynthesis).

**Heterotrophic:** Organisms that obtain food by consuming other organisms.

**Unicellular:** Single-celled organism.

**Multicellular:** Organism composed of many cells working together.

**Diploblastic:** Having two tissue layers (ectoderm and endoderm).

**Triploblastic:** Having three tissue layers (ectoderm, mesoderm, and endoderm).

**Bilateral Symmetry:** Body plan where left and right halves are mirror images.

**Radial Symmetry:** Body organized around a central axis, like a wheel.

**Coelom:** A body cavity fully lined with mesoderm; contains internal organs.

**Acoelomate:** No body cavity; tissues fill space between outer and inner layers.

**Pseudocoelomate:** False body cavity; not fully lined with mesoderm.

**Cephalization:** Development of a distinct head with sensory and nervous structures.

**Segmentation:** Division of body into repeating units or segments.

**Ectothermic:** Cold-blooded; body temperature varies with environment (fish, reptiles).

**Endothermic:** Warm-blooded; maintains constant body temperature (birds, mammals).

**Closed Circulatory System:** Blood circulates through vessels; more efficient (annelids, chordates).

**Open Circulatory System:** Blood bathes organs directly in hemocoel (arthropods, mollusks).

**Notochord:** Supporting rod along body; becomes vertebral column in vertebrates.

**Amniotic Eggs:** Eggs with protective membranes; can be laid on land (reptiles, birds, mammals).

**Viviparity:** Live birth; embryo develops inside mother's body.

**Saprophytic Nutrition:** Feeding on dead organic matter; characteristic of fungi.

**Photosynthesis:** Process by which plants make food using light energy.

**Metamorphosis:** Transformation from larval to adult form; dramatic in amphibians.

**Regeneration:** Ability to regrow lost body parts.

