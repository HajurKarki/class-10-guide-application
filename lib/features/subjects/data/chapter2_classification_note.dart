**CLASS MAMMALIA (Mammals):**

**Key Adaptation: Internal Development + Lactation**

**Defining Mammalia Feature:**
- **Mammary Glands** produce milk (nutrient-rich secretion) to feed young
- Only mammals have this
- Milk composition varies by species (whale milk: 50% fat vs. human milk: 4% fat)

**Other Mammalian Characteristics:**
- **Endothermic**: Maintain constant temperature (35-38Â°C)
- **Hair/Fur**: Insulation, sensory (whiskers), pheromone dispersal
- **4-chambered Heart**: Efficient oxygenated blood delivery
- **Diaphragm**: Muscular sheet for efficient ventilation
- **Specialized Teeth**: Incisors (cutting), canines (tearing), premolars/molars (grinding)
- **Closed Circulatory System**: Blood in vessels
- **Diphyodont**: Two sets of teeth (deciduous/baby, permanent)
- **Complex Brain**: Neocortex for higher cognition
- **Amniotic Eggs** (most species) OR live birth

**Mammalian Intelligence:**
- Most intelligent vertebrates (besides humans)
- Tool use: chimpanzees, dolphins, elephants, crows
- Communication: complex vocalizations, sign language (dolphins, great apes)
- Social structures: family groups, hierarchies
- Memory: long-term learning, cultural transmission

**Evolutionary Origin:**
- Evolved from synapsids (mammal-like reptiles)
- 300+ million years ago
- Early mammals: small, nocturnal, insectivorous
- Diversified after dinosaur extinction (66 million years ago)

**Sub-classes:**

*Monotremata* (Egg-laying Mammals):
- Retained ancestral egg-laying
- Platypus: only mammal with venomous spurs (males), electroreception, 10 sex chromosomes
- Echidna: spiny anteater, long sticky tongue
- Modern survivors of ancient lineage

*Marsupialia* (Pouch Mammals):
- Incomplete placenta
- Short gestation (12-13 days in kangaroo)
- Young finish development in pouch
- Kangaroo: largest marsupial, hop at 70 km/h
- Koala: eucalyptus specialist
- Mostly Australian (isolated island = unique evolution)

*Placentalia* (Placental Mammals):
- Complete placenta for nutrient/waste exchange
- Longer gestation (humans: 9 months)
- Diverse orders:

**Orders of Placentals:**

*Primates* (Humans, Apes, Monkeys):
- Grasping hands with opposable thumbs
- Forward-facing binocular eyes (depth perception for tree-living)
- Reduced sense of smell
- Long childhood dependency
- Complex social behavior
- Humans (*Homo sapiens*): 6-7 million years divergence from chimps

*Carnivora* (Cats, Dogs, Bears):
- Carnassial teeth: shear flesh
- Powerful limbs and claws
- Excellent predators
- Cooperative hunting (lions, wolves, orcas)

*Cetacea* (Whales, Dolphins):
- Aquatic mammals (returned to ocean)
- Streamlined body, flippers (modified limbs)
- Blowhole for breathing
- Intelligence: complex communication, problem-solving
- Largest animal ever: blue whale (30 meters, 200 tons)
- Echolocation: produce ultrasonic clicks, listen for echoes
- Migration: humpbacks travel 25,000 km annually

*Proboscidea* (Elephants):
- Largest land mammals (4-6 meters, 6 tons)
- Trunk: 40,000+ muscles, incredible dexterity
- Long-lived (60+ years)
- Strong memory, intelligence
- Social: matriarchy system, mourning behavior
- Endangered by poaching (ivory trade)

*Chiroptera* (Bats):
- Only mammals with true flight
- Echolocation: sophisticated ultrasonic navigation
- Diverse: 1,300+ species
- Roles: insectivorous (pest control), frugivorous (seed dispersal), nectarivorous (pollination)
- Controversial: rabies vector, but essential pollinators

*Rodentia* (Mice, Rats, Squirrels):
- Most diverse mammal order (40% of mammalian species)
- Continually growing incisors
- Gnawing lifestyle
- Prolific breeders (population control challenge)
- Some (mice, rats): disease vectors, crop pests

*Artiodactyla* (Even-toed Ungulates):
- Deer, pigs, cattle, sheep, camels, hippopotamus
- Even number of toes (2 or 4)
- Herbivorous (mostly)
- Specialized digestive systems: ruminants (cows, sheep) regurgitate and chew cud

*Perissodactyla* (Odd-toed Ungulates):
- Horses, rhinos, tapirs
- Odd number of toes (1 or 3)
- Large herbivores
- Horses: specialized for running
- Rhinos: critically endangered (poaching)

*Lagomorpha* (Rabbits, Hares):
- Herbivorous
- Large ears (thermoregulation, predator detection)
- Powerful hind legs (escape)
- Two pairs of incisors in upper jaw (vs. one in rodents)

