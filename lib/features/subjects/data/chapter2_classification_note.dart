### **KINGDOM ANIMALIA - Deep Dive**

**Understanding Animal Phyla Through Body Plan Evolution:**

As we move through phyla, observe increasing complexity:
- **Sponges:** No true tissues â†’ **Coelenterates:** Two tissue layers â†’ **Flatworms:** Three layers, no coelom
- **Roundworms:** Pseudo-coelom â†’ **Annelids:** True coelom, segmented â†’ **Arthropods:** Highly specialized segments
- **Mollusks:** Soft-bodied with specialized parts â†’ **Echinoderms:** Radial as adults, water vascular
- **Chordates:** Most complex, internal skeleton, closed circulation

**PORIFERA (Sponges) - *Sycon*, *Leucosolenia*:**

**Why simplest animals?**
- No brain, nerve cells, or defined organs
- Body is mostly hollow with tiny pores (ostia) and large opening (osculum)
- Water flows through: ostia â†’ cavity â†’ osculum
- Filter feeding: trap bacteria and plankton, digest internally in food vacuoles
- Regeneration extreme: sieve through cloth, cells reassemble into new sponge

**Cells:**
- Pinacocytes: outer covering cells
- Choanocytes: collar cells with flagella, generate water current
- Amoebocytes: mobile cells, distribute nutrients

**Reproduction:**
- Asexual: budding (small bud becomes new sponge)
- Sexual: sperm and eggs through water column, larvae settle

**Ecological Role:**
- Biomedical research (sponge compounds used for cancer drugs)
- Water purification (filter hundreds of liters daily)
- Symbiotic relationships with bacteria/algae

