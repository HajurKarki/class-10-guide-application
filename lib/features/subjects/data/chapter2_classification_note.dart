### **KINGDOM FUNGI - Deep Dive**

**Unique Features Making Fungi Special:**

1. **Chitin Cell Wall** - Like arthropods, not like plants (cellulose)
   - Chitin: N-containing polysaccharide
   - Gives structural strength and flexibility
   - Makes fungi tough and resilient

2. **Saprophytic Nutrition** - Extracellular digestion
   - Secretes enzymes outside the body
   - Breaks down organic matter externally
   - Absorbs nutrient solution back into hyphae
   - Unlike animals who ingest and digest internally

3. **Hyphal Structure**
   - Hyphae: elongated filaments
   - Mycelium: collective network of hyphae
   - Septate (with walls) vs. Aseptate (no walls)
   - Allows rapid growth through substrate

**Fungal Reproduction:**

**Asexual:**
- **Spores**: microscopic, dispersed by wind/water
- **Budding**: small outgrowth develops into new organism
- **Fragmentation**: mycelium breaks into pieces, each grows

**Sexual:**
- Involves fusion of compatible mating types
- Formation of specialized spore structures (zygospores, ascospores, basidiospores)
- More genetic variation than asexual

**Major Groups with Examples:**

*Zygomycetes* (*Rhizopus nigricans* - bread mold):
- Rapid colonizers
- Produce zygospores (result of fusion of two hyphae)
- Common in bread, fruits, vegetables
- Visible white/gray fuzz is mycelium, black structures are sporangia
- Can cause food spoilage within days

*Ascomycetes* (including *Saccharomyces cerevisiae* - baker's yeast):
- Produce ascospores in sac-like asci
- Includes truffles, morels, cup fungi
- Yeast: unicellular ascomycete, reproduces by budding
- Uses: bread rising, alcohol fermentation, wine production
- *Claviceps purpurea*: ergot fungus, historically caused ergotism

*Basidiomycetes* (Mushrooms):
- Visible fruiting bodies we recognize as mushrooms
- Produce basidiospores on club-shaped basidia
- Include puffballs, shelf fungi, stinkhorns
- Mycelium hidden in soil/wood; fruiting body is reproductive structure
- *Agaricus bisporus*: common edible mushroom

*Deuteromycetes* (Imperfect Fungi):
- Reproduction method unclear (artificial classification)
- Includes *Penicillium notatum* - source of penicillin antibiotic
- *Aspergillus* - can cause respiratory infections or produce aflatoxins
- *Candida albicans* - causes yeast infections

**Importance of Fungi:**

**Beneficial:**
- **Decomposition:** Break down dead matter, return nutrients to soil (essential for nutrient cycling)
- **Antibiotics:** Penicillin, cephalosporin (life-saving medicines)
- **Food:** Mushrooms, yeasts for brewing and baking
- **Fermentation:** Yogurt, cheese, soy sauce production
- **Symbiosis:** Mycorrhizal associations with plant roots

**Harmful:**
- **Plant Diseases:** Powdery mildew, rusts, blights (crop failures)
- **Human Infections:** Athlete's foot (tinea), ringworm (dermatophytes), candida
- **Mycotoxins:** Aflatoxin-producing fungi contaminate food crops
- **Allergies:** Spores trigger allergies and asthma

