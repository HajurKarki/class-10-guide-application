**COELENTERATA (Cnidarians) - *Hydra*, *Anemone*, *Corals*:**

**Key Innovation: Stinging Cells (Cnidocytes)**
- Contain nematocysts - harpoon-like structures
- Fire explosively when triggered
- Inject toxin into prey
- Only cnidarians have this weapon

**Body Forms:**
1. **Polyp** - cylindrical, attached (e.g., Hydra, sea anemone)
2. **Medusa** - bell-shaped, free-swimming (e.g., jellyfish)
3. **Polymorphic** - both forms in life cycle (e.g., corals)

**Radial Symmetry Advantage:**
- No front or back - can sense threats/food from all directions
- Efficient for sessile life or drifting

**Examples:**

*Hydra* (*Hydra viridis*):
- Tiny freshwater predator (2-20mm)
- Reproduces asexually by budding
- Amazing regeneration (even if cut in pieces, reforms)
- Turns green due to symbiotic algae
- Model organism for developmental biology

*Sea Anemone* (*Actinia equina*):
- Solitary coral, looks like flower
- Tentacles around mouth trap fish
- Sessile on rocks

*Corals* (*Acropora*, *Porites*):
- Symbiotic with zooxanthellae (algae)
- Algae photosynthesize, feed coral; coral provides nutrients
- Build reefs: skeletons accumulate
- Highly threatened by ocean warming and acidification

**Ecological Importance:**
- Coral reefs: most biodiverse ecosystems
- Support 25% of marine life despite covering <1% of ocean floor
- Protect coasts from storms
- Provide food and income for 500 million people
- Rapidly declining (bleaching events)

