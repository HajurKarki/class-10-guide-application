### **KINGDOM PROTISTA - Deep Dive**

**Evolutionary Significance:**
Protists represent the evolutionary bridge between prokaryotes (Monera) and multicellular eukaryotes. Many show characteristics of animals, plants, or fungi simultaneously - hence the diversity.

**Protozoans (Animal-like Protists):**

*Amoeba* (*Amoeba proteus*):
- Moves using pseudopodia (false feet) - temporary projections of cytoplasm
- No fixed shape - constantly changing
- Nucleus visible in center
- Feeds by engulfing bacteria and algae
- Reproduces by binary fission
- Found in freshwater ponds

*Paramecium*:
- Covered with cilia (hair-like organelles) for movement
- Oval-shaped with a gullet (mouth-like structure)
- Nuclei: micronucleus (reproduction) and macronucleus (feeding)
- Feeds on bacteria
- Conjugation for sexual reproduction
- Found in freshwater, excellent lab organism

*Plasmodium* (causes Malaria):
- Parasitic protozoan
- Transmitted by Anopheles mosquito
- Destroys red blood cells
- Causes recurring fever and chills
- One of the deadliest human parasites
- Millions of deaths annually

**Algae (Plant-like Protists):**

**Why are they not plants?**
- Eukaryotic, but mostly unicellular or simple multicellular
- Lack true roots, stems, leaves, flowers
- Simpler reproductive structures
- Diverse pigments beyond chlorophyll

*Spirogyra*:
- Filamentous green alga
- Forms "pond scum" in stagnant water
- Beautiful spiral chloroplast arrangement
- Reproduces by conjugation (temporary tube between cells for genetic exchange)
- Important aquatic producer

*Volvox*:
- Colonial alga - many individual cells forming sphere
- Shows division of labor (somatic vs. reproductive cells)
- Rolling movement gives "rolling ball" appearance
- Example of evolution toward multicellularity

*Chlamydomonas*:
- Unicellular green alga
- Two flagella for movement
- Used in genetic research
- Common in fresh water

**Importance of Algae:**
- Produce ~50% of Earth's oxygen (more than all forests combined!)
- Base of aquatic food chains
- Source of nutritional supplements and cosmetics
- Seaweed harvested for food (sushi, nori)
- Biofuel potential

**Slime Molds:**
- Fungal-like protists (similar feeding mechanism to fungi)
- Feed by engulfing particles (like amoeba) but form multicellular structure
- Plasmodium stage - multinucleate mass
- Fruiting bodies produce spores
- Example: *Physarum polycephalum* - used in research

