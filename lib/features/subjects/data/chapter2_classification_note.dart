**CLASS REPTILIA (Reptiles):**

**Key Adaptation: Fully Terrestrial** (no aquatic larval stage)

**Reptilian Features:**
- **Amniotic Eggs**: Protective membranes allow development on land (no free-swimming larval stage)
- **Dry, Scaly Skin**: Waterproof (reduces water loss)
- **Ectothermic**: Cold-blooded (behavior-dependent thermoregulation - basking)
- **3-chambered Heart**: Crocodilians have 4-chambered (like birds/mammals)
- **Claws on Digits**: for climbing/digging
- **Internal Fertilization**: Male introduces sperm directly

**Reptilian Evolution from Amphibians:**
- Lost dependence on water for reproduction
- Skin became waterproof (keratin scales)
- Eggs became protected (amniotic membrane)
- Allowed colonization of drier habitats

**Types:**

*Snakes* (*Natrix*, *Vipera*):
- Legless (reduced limbs or lost entirely)
- Overlapping scales for movement (undulation)
- Forked tongue: chemoreception (collects scent particles)
- Venom: modified saliva in some species (vipers, cobras)
- Heat-sensing pits: detect infrared (prey detection)
- Jaw dislocation: swallow large prey whole

*Lizards* (*Lacerta*, *Varanus*):
- Four legs (typical)
- Eyelids (unlike snakes)
- Ear openings visible
- Autotomy: drop tail when threatened (regenerates)
- Monitor lizards: large, intelligent predators
- Chameleons: color change (pigment cells), prehensile tail

*Turtles and Tortoises* (*Testudo*, *Chelone*):
- Shell: fused ribs and vertebrae covered with scutes (plates)
- Protective armor
- Slow-moving, long-lived (100+ years possible)
- Aquatic (turtles): streamlined shell, flippers
- Terrestrial (tortoises): domed shell, columnar legs
- Marine turtles: migrate thousands of km, endangered by fishing nets/plastic

*Crocodilians* (*Crocodylus*, *Alligator*):
- Large, powerful predators
- 4-chambered heart (unique for reptiles)
- Saltwater tolerance (salt glands)
- Parental care (guard nests)
- Ancient lineage (survive since dinosaur extinction)

**Ecological Role:**
- Predators: control rodent/insect populations
- Prey: food for birds, large carnivores
- Indicators of habitat quality

