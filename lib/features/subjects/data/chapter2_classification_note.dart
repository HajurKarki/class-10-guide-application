## Topic 3: Five Kingdom System - Detailed Characteristics

### **KINGDOM MONERA - Deep Dive**

**Prokaryotic vs. Eukaryotic:**

Prokaryotic (Monera/Bacteria):
- No membrane-bound nucleus
- DNA floating freely in nucleoid region
- No membrane-bound organelles
- Ribosomes are 70S (smaller)
- Unicellular
- Cell wall made of peptidoglycan (bacteria) or pseudopeptidoglycan (archaea)

Eukaryotic (all others):
- Membrane-bound nucleus containing DNA
- DNA organized into chromosomes
- Membrane-bound organelles (mitochondria, endoplasmic reticulum, Golgi, etc.)
- Ribosomes are 80S (larger)
- Can be unicellular or multicellular
- Diverse cell wall compositions

**Bacterial Reproduction:**

*Binary Fission* - asexual reproduction:
1. DNA replicates
2. Cell elongates
3. Proteins hold replicated DNA
4. Cell membrane pinches
5. Two identical daughter cells form

**Bacterial Shapes (Morphology):**
- **Cocci** - spherical (e.g., *Streptococcus*)
- **Bacilli** - rod-shaped (e.g., *E. coli*)
- **Spirilla** - spiral/twisted (e.g., *Vibrio*)

**Beneficial Bacteria:**
- Yogurt and cheese production (*Lactobacillus*)
- Nitrogen fixation in soil (*Rhizobium*)
- Vitamin K production in intestines
- Biotechnology applications
- Decomposition in ecosystems

**Harmful Bacteria:**
- Disease-causing pathogens (*Streptococcus pyogenes* - strep throat)
- *Salmonella* - food poisoning
- *Mycobacterium tuberculosis* - tuberculosis
- *Vibrio cholerae* - cholera
- *Corynebacterium diphtheriae* - diphtheria

