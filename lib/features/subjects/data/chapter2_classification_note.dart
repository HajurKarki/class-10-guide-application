**ECHINODERMATA (Echinoderms) - *Asterias*, *Echinometra*:**

**Unique Characteristics:**

1. **Water Vascular System** (no other animal has this)
   - Network of water-filled tubes
   - Tube feet: hydraulic structures extend/retract for locomotion and feeding
   - Ampulla: muscular bulb contracts to extend tube foot
   - Allows slow, steady movement on any surface

2. **Radial Symmetry as Adults** (bilateral as larvae)
   - Body organized around central axis
   - 5-armed body plan (pentameric)
   - Each arm is nearly complete organism

3. **Endoskeleton**
   - Internal skeleton of calcium carbonate plates
   - Covered by skin
   - Spines project outward (echinoderm = spiny-skin)
   - Unlike exoskeleton, doesn't restrict growth

4. **Regeneration**
   - Can regrow lost arms
   - Central disc regenerates arm in 1-2 years
   - Regenerated arm starts as tiny bud

**Examples:**

*Starfish* (*Asterias*):
- 5 arms (though some have more) with tube feet on underside
- Predatory: feeds on clams by inserting stomach between shells
- Movement: tube feet create stepping motion
- Feeding: extrudes stomach into prey, digests externally, retracts

*Sea Urchin* (*Echinometra*):
- Globular body covered with long spines
- Spines: defense and locomotion
- Tube feet for movement and food collection
- Feeds on algae and organic debris
- Sea urchin roe (eggs) considered delicacy in Japan

*Sea Cucumber* (*Holothurian*):
- Elongated, worm-like body
- Tentacles around mouth (modified tube feet)
- Deposit feeders: eat sediment
- Defense: expel toxic Cuvierian tubules to confuse predators

**Ecological Role:**
- Herbivores (sea urchins): control algae
- Detritivores (sea cucumbers): process sediment
- Indicators of ecosystem health
- Overharvesting threatens populations

