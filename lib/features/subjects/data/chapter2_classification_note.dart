**ANNELIDA (Segmented Worms) - *Lumbricus terrestris* (Earthworm):**

**Revolutionary Feature: Segmentation**
- Body divided into repeated rings
- Each segment has similar organs (nervous, muscular, circulatory systems)
- Allows specialization of segments
- Permits movement without exoskeleton (muscular hydrostat principle)

**Second Revolution: Closed Circulatory System**
- Blood circulates through vessels
- More efficient than open systems (maintains pressure)
- Allows smaller organisms to function

**Earthworm Anatomy:**
- Mouth: at anterior (front)
- Pharynx: muscular suction apparatus
- Esophagus: food transport
- Crop: food storage
- Gizzard: muscular grinding chamber
- Intestines: absorption
- Anus: posterior (rear)
- Aortic arches (hearts): 5 pairs pump blood
- Nephridia: excretory organs in each segment

**Hermaphroditic Reproduction:**
- Both male and female reproductive organs
- Cocoon formation: two worms exchange sperm
- Cocoon protects developing eggs

**Ecological Importance:**
- Soil aeration: burrowing creates air spaces
- Fertilization: decompose organic matter, return nutrients
- Earthworm casts improve soil structure
- Charles Darwin studied earthworms' effect on soil
- Burrowing enhances water infiltration

**Other Annelids:**
- **Leeches** (*Hirudo medicinalis*): anticoagulant saliva, used in reconstructive surgery
- **Polychaetes** (*Neanthes*, *Eunice*): marine worms, some bioluminescent

