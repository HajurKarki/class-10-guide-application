**ARTHROPODA (Arthropods) - *Musca*, *Periplaneta*, *Cancer*:**

**Why most successful animal phylum?**
- Over 1 million described species (80% of all animals)
- Conquered every habitat (land, sea, air)
- Exceptional adaptations and diversity

**Defining Features:**

1. **Jointed Legs** (arthro=joint, poda=foot)
   - Hydraulic system: muscles contract, joints bend
   - Allow fine control and rapid movement

2. **Exoskeleton**
   - Hard outer skeleton made of chitin and proteins
   - Advantages: protection, waterproofing, muscle attachment
   - Disadvantages: must molt to grow (vulnerable during molt)
   - Molting process: new skeleton forms beneath, old splits and sheds

3. **Segmentation** (like annelids)
   - Body divided into regions with specialized functions
   - Head: sensory apparatus
   - Thorax: locomotion (legs)
   - Abdomen: reproduction, digestion

4. **Open Circulatory System**
   - Blood (hemolymph) bathes organs in hemocoel
   - Heart pumps blood
   - Less efficient than closed, but sufficient for small arthropods

5. **Efficient Respiration**
   - Terrestrial: tracheal system (air tubes reaching cells)
   - Aquatic: gills or gill-like structures
   - Small size means high surface-area-to-volume ratio (efficient gas exchange)

**Major Classes:**

*Insecta* (Insects) - 1 million+ species:
- Head, thorax, abdomen (three body regions)
- 6 legs (three pairs on thorax)
- Wings (0, 1, or 2 pairs)
- Compound eyes and antennae
- Examples:
  - Butterflies (*Lepidoptera*): taste with feet, drink with proboscis
  - Ants (*Formicidae*): complex societies, chemical communication
  - Bees (*Apidae*): pollinate crops, produce honey
  - Cockroaches (*Periplaneta*): ancient group (320 million years), survivors
  - Dragonflies (*Odonata*): aerial hunters, excellent vision
- **Complete Metamorphosis**: egg â†’ larva (caterpillar/maggot) â†’ pupa â†’ adult
  - Larva looks completely different from adult
  - Allows different ecological niches (caterpillar eats leaves, butterfly drinks nectar)
- **Incomplete Metamorphosis**: egg â†’ nymph â†’ adult (gradual)
  - Nymph looks like mini adult
  - Common in grasshoppers, bugs

*Arachnida* (Spiders, Scorpions, Ticks):
- Head and thorax fused (cephalothorax), separate abdomen
- 8 legs (4 pairs) - distinguishes from insects
- No antennae
- Pedipalps (leg-like appendages) used for sensing and feeding
- Spinnerets: produce silk threads
- Spiders: predatory, beneficial (eat insects)
- Scorpions: venomous stinger, glow under UV light
- Ticks: parasitic, disease vectors (Lyme disease from *Ixodes* ticks)

*Crustacea* (Crabs, Shrimp, Lobsters):
- Aquatic (mostly)
- Appendages: 5+ pairs of legs, antennae, mouthparts
- Hard shell (exoskeleton heavily calcified with calcium)
- Examples:
  - Crab: sideways walking, pincers (chelipeds)
  - Shrimp: rapid backward swimming escape
  - Lobster: largest arthropods (can exceed 1 meter)

**Importance:**
- **Pollination**: Bees pollinate 75% of food crops
- **Pest Control**: Spiders, parasitic wasps, ladybugs eat pests
- **Decomposition**: Flies, beetles break down organic matter
- **Food Source**: Shrimp, crabs, insects (crickets, mealworms) provide protein
- **Medical**: Some arthropods produce silk for medical sutures
- **Harmful**: Mosquitoes (malaria, dengue), ticks (Lyme disease), locusts (crop destruction)

