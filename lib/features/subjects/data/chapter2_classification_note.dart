**NEMATODA (Roundworms) - *Ascaris lumbricoides*:**

**Improvements Over Flatworms:**
- Pseudocoelom (false body cavity) allows internal organs to move
- Unsegmented, cylindrical body (more efficient locomotion)
- Separate mouth and anus (complete digestive tract)

**Structure:**
- Cuticle covering
- Muscle layers enabling undulating movement
- Nerve ring around pharynx
- Reproductive organs dominate body cavity

**Important Species:**

*Ascaris lumbricoides* (large roundworm):
- Infects intestines (humans primary host)
- 1 billion+ infected people globally
- Largest intestinal parasite in humans (20-35 cm long)
- Egg transmission: contaminated food/water
- Effects: malnutrition, anemia, intestinal blockage, developmental delay
- More common in children in tropical/subtropical regions

*Hookworm* (*Necator americanus*):
- Penetrates skin (often barefoot exposure)
- Hooks onto intestinal wall, feeds on blood
- Chronic infection causes anemia and weakness
- 600 million+ infected people

*Pinworm* (*Enterobius vermicularis*):
- Common in children
- Causes itching, especially at night
- Transmission: contaminated hands/fomites
- Least dangerous but most annoying

**Prevention:**
- Proper sanitation and water treatment
- Wearing shoes in contaminated areas
- Health education and deworming programs

