**CLASS AMPHIBIA (Amphibians):**

**Key Adaptation: Dual Life** (amphibi = both, bios = life)

**Aquatic Larval Stage:**
- Tadpole/pollywog: aquatic herbivore
- Gills for respiration
- Tail for swimming
- Feeds on algae

**Terrestrial Adult Stage:**
- Frog/toad: terrestrial predator
- Lungs for respiration
- Legs for hopping
- Feeds on insects

**Metamorphosis Process:**
1. Tadpole develops hind legs first (hindlimbs)
2. Front legs emerge (forelimbs)
3. Tail shortens and resorbs
4. Gills close, lungs develop
5. Diet shifts from plants to insects
6. Overall body shape transforms

**This Complete Metamorphosis:**
- Takes 3-12 months depending on species
- Dramatic remodeling of tissues
- Allows exploitation of different food sources at different life stages

**Amphibian Features:**
- **Moist Skin**: Permeable to water, requires humid environment
- **Cutaneous Respiration**: Some gas exchange through skin
- **External Fertilization**: Eggs in water (no amniotic membrane)
- **No Scales**: Unlike reptiles
- **3-chambered Heart**: Incomplete separation of circuits (one ventricle with partial septum)

**Types:**

*Frogs and Toads* (*Rana*, *Bufo*):
- Tailless (adults)
- Powerful hind legs for jumping
- Large mouth, sticky tongue for insect capture
- Vocal sacs produce calls (communication, mating)
- Toads: bumpy skin (poison glands), adapted to drier habitats
- Frogs: smooth skin, stay near water

*Salamanders* (*Salamandra*, *Triturus*):
- Retain tail (throughout life)
- Lizard-like body
- Less specialized than frogs
- Some aquatic (newts), some terrestrial
- Lungless salamanders: respire through skin

*Caecilians* (*Ichthyophis*):
- Limbless (worm-like)
- Tropical/subtropical
- Burrowing lifestyle
- Poorly known, least studied vertebrates

**Ecological Role:**
- **Bioindicators**: Skin permeability makes them sensitive to pollution
- Amphibian population declines indicate ecosystem stress
- Skin toxins: some species produce alkaloid toxins (used for poison darts)
- Food web: tadpoles filter algae, adults eat insects, preyed upon by birds/snakes

**Conservation Concern:**
- Rapid global decline (chytrid fungus, habitat loss, pollution, climate change)
- ~1/3 of amphibian species threatened
- Loss of amphibians disrupts ecosystems

