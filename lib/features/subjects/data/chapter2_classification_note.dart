**PLATYHELMINTHES (Flatworms) - *Planaria*, *Taenia*:**

**First Triploblastic Animals:**
- Three tissue layers allow complex organs
- Bilateral symmetry means front/back development (head with sensory organs)
- No coelom yet

**Structure:**
- Flat, leaf-shaped body
- Cephalization: head with eyes (ocelli - simple light-sensitive spots)
- Nervous system: brain ganglia with nerve cords
- Digestive tract: mouth but only one opening (dead-end gut)
- No anus - undigested material exits through mouth

**Types:**

*Planaria* (*Dugesia*) - Free-living:
- Freshwater organism
- Feeds on small organisms
- Remarkable regeneration: cut in half, each half grows new parts
- Reproduction: sexual (hermaphroditic - both male/female organs)
- Model organism for regeneration research

*Parasitic Flatworms:*

**Tapeworm** (*Taenia solium* - pork tapeworm):
- Lives in intestines (humans are primary host)
- Highly adapted to parasitic life:
  - No digestive tract (nutrients absorbed directly through skin)
  - Thick cuticle resists digestion
  - Highly reproductive (millions of eggs)
- Structure: scolex (head with suckers), proglottids (body segments with organs)
- Infection: eating undercooked infected pork
- Effects: anemia, malnutrition, can be several meters long
- Treatment: antiparasitic drugs (praziquantel)

**Fluke** (*Fasciola hepatica* - liver fluke):
- Lives in liver and bile ducts
- Requires snails as intermediate host
- Causes fascioliasis (liver disease)
- Affects livestock more than humans

**Medical Importance:**
- Affect 300 million+ people globally
- Cause anemia, malnutrition, developmental problems in children
- Prevention: proper cooking, sanitation, health education

