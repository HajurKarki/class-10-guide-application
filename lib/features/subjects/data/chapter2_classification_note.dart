**CHORDATA (Chordates):**

**Defining Features** (at some point in life):
1. **Notochord** - supporting rod running dorsal
2. **Dorsal Nerve Cord** - neural tube above notochord
3. **Pharyngeal Gill Slits** - throat slits (respiration or filter feeding)
4. **Post-anal Tail** - extends beyond anus

**Major Distinction: Vertebrates vs. Non-vertebrates**

**Non-Vertebrate Chordates:**

*Hemichordates* (*Balanoglossus* - acorn worm):
- Worm-like burrower in sand
- Partially exhibits chordate features
- Bridges between invertebrates and vertebrates

*Urochordata* (Tunicates - sea squirts):
- Tunic (outer covering) of cellulose
- Filter feeders
- Tadpole larva has clear chordate features
- Adult loses notochord and nerve cord (regresses)

**Vertebrate Chordates:**

Key innovation: **Vertebral Column**
- Segments of bone or cartilage (vertebrae) surrounding nerve cord
- Notochord becomes intervertebral discs
- Protects spinal cord
- Allows flexibility and support for large body sizes
- Enables evolution of specialized body regions (cervical, thoracic, lumbar)

