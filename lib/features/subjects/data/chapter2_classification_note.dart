### **KINGDOM PLANTAE - Deep Dive**

**Plant Evolution - Why Classification Makes Sense:**

Plants evolved to land in stages, each division showing new adaptations:

**Bryophytes â†’ Pteridophytes â†’ Gymnosperms â†’ Angiosperms**
(Non-vascular â†’ Vascular/Seedless â†’ Seed-bearing/Naked â†’ Seed-bearing/Enclosed)

**Bryophytes (Mosses, Liverworts) - *Riccia*, *Funaria*:**

**Why called "non-vascular"?**
- Lack xylem (water transport) and phloem (food transport)
- Water moves cell-to-cell directly
- No true roots, stems, leaves
- Limited to moist habitats (need water for reproduction)
- Small size (max 1 meter) - can't support heavy structures without vascular tissue

**Life Cycle (Alternation of Generations):**
- **Gametophyte** (n) = Dominant stage - the moss plant you see
  - Produces gametes (eggs, sperm)
  - Sperm requires water to swim to egg
- **Sporophyte** (2n) = Dependent stage - grows from fertilized egg
  - Releases spores
  - Short-lived, attached to gametophyte

**Ecological Niche:**
- Pioneer species colonizing bare rock/soil
- Build up soil for other plants
- Indicator of clean air (sensitive to pollution)
- Moisture retention in ecosystems

**Pteridophytes (Ferns) - *Dryopteris*:**

**Why called "vascular but seedless"?**
- Have xylem and phloem (can grow larger, absorb more water)
- Reproduce by spores, not seeds
- Can grow in drier habitats than bryophytes (but still need moisture)
- Typical fern height: 0.3-2 meters

**Life Cycle:**
- **Sporophyte** (2n) = Dominant stage - visible fern plant
  - Fronds (leaves) with sporangia on underside (look like brown dots)
  - Each sporangium releases ~64 spores
- **Gametophyte** (n) = Independent, small (few mm)
  - Green, heart-shaped prothallus
  - Produces sperm and eggs
  - Sperm swims to egg in water film on prothallus

**Features:**
- Fronds uncoil in characteristic fiddlehead spiral (uncinate)
- Roots, stems (rhizomes), true leaves
- No flowers or seeds
- Ancient group: ferns date back 360 million years, survived dinosaurs

**Modern Uses:**
- Ornamental plants in gardens
- Fossil fuels (coal includes ancient fern material)
- Some ferns edible (fiddleheads)

**Gymnosperms (Conifers, Ginkgo) - *Pinus*, *Cedrus*:**

**Why called "naked-seeded"?**
- Produce seeds that are NOT enclosed in fruit
- Seeds exposed on cone scales
- Wind pollination (no need for showy flowers)

**Characteristics:**
- Fully vascular with xylem and phloem
- Woody, perennial plants
- Cones: female (ovulate) cones contain seeds; male (pollen) cones release pollen
- Needle or scale-like leaves (reduce water loss)
- Resinous wood (fragrant, insect-resistant)

**Life Cycle:**
- **Sporophyte dominant** - the tree we see
- **Gametophyte reduced** - pollen grain (male) and ovule (female)
- **Pollination:** Wind carries pollen from male cone to female cone
- Seeds develop inside cone for 2-3 years before release

**Diversity:**
- Conifers: Pine (*Pinus*), Fir (*Abies*), Spruce (*Picea*), Cedar (*Cedrus*), Larch
- Non-conifers: Ginkgo (living fossil, unchanged 200 million years), Cycads

**Ecological Importance:**
- Dominate high altitude and high latitude forests (taiga/boreal forest)
- Major timber source
- Cone-bearing plants feed wildlife (squirrels, birds, bears)
- Oldest living trees: Bristlecone pines (>4000 years old)

**In Nepal:**
- Blue Pine (*Pinus wallichiana*) - common in Himalayas
- Fir (*Abies spectabilis*) - alpine regions
- Cedar (*Cedrus deodara*) - valued timber, sacred in Hindu/Buddhist traditions

**Angiosperms (Flowering Plants) - *Rosa*, *Mangifera*:**

**Why called "enclosed-seeded"?**
- Seeds develop INSIDE a fruit
- Fruit develops from ovary wall, protecting seeds
- Allows seed dispersal by animals eating fruit

**Why are they most successful (300,000+ species)?**

1. **Flowers** - Reproductive organs enclosed in colorful structures
   - Attract pollinators (insects, birds, bats, even mammals)
   - More reliable pollination than wind-dependent gymnosperms

2. **Double Fertilization** - Unique to angiosperms
   - One sperm fuses with egg (produces embryo)
   - Other sperm fuses with polar nuclei (produces endosperm - nutritive tissue)
   - Efficient use of energy

3. **Fruits** - Protect and disperse seeds
   - Animals eat fruit, disperse seeds in feces far from parent
   - Dry fruits (nuts, pods) spread by wind or animals
   - Allows colonization of new habitats

4. **Rapid Reproduction** - Short generation time
   - Can reproduce within 1-2 years (vs. 20+ years for conifers)
   - Adapt quickly to environmental changes

**Angiosperm Diversity:**

*Monocots* (single seed leaf):
- Parallel leaf veins
- Flower parts in multiples of 3
- No secondary growth (no wood)
- Examples: Grasses, lilies, orchids, palms, corn, wheat, rice

*Dicots* (two seed leaves):
- Branching leaf veins
- Flower parts in multiples of 4-5
- Secondary growth (woody shrubs/trees)
- Examples: Beans, roses, sunflowers, apple, rose, mango, mustard

**Examples in Nepal:**
- Rhododendron - national flower, covers Himalayan foothills
- Mango (*Mangifera indica*) - important fruit crop
- Mustard - oil seed crop
- Orchids - diverse alpine species

