**MOLLUSCA (Mollusks) - *Helix*, *Sepia*, *Venus*:**

**Unique Features:**

1. **Muscular Foot**
   - Hydrostatic principle: fluid-filled muscular structures create movement
   - Snails: undulating contractions move foot forward
   - Clams: digging foot burrows into sand
   - Squid: modified into arms with suckers

2. **Mantle**
   - Tissue covering internal organs
   - Secretes shell in most species
   - Contains gills for respiration

3. **Radula** (in many)
   - Ribbon-like organ with thousands of teeth
   - Rasps food surface
   - Unique among animals
   - Like a biological file/saw

**Major Classes:**

*Gastropoda* (Snails, Slugs):
- Foot for crawling
- Head with eyes (on tentacles in land snails)
- Radula for feeding
- Snails: external shell provides protection
- Slugs: lost shell, moist skin vulnerable to desiccation
- Hermaphroditic (self-fertilization possible but rare)

*Bivalvia* (Clams, Oysters, Mussels):
- Two shells (valves) hinged together
- No head (sessile or slow-moving)
- Filter feeders: draw water through gills, trap plankton
- Form pearls: irritant coated with nacre (mother-of-pearl)
- Ecological importance: filter water, stabilize substrate

*Cephalopoda* (Octopus, Squid, Cuttlefish):
- Most intelligent invertebrates (brain comparable to small mammals)
- Tentacles/arms with suckers
- Jet propulsion: squirt water for rapid movement
- Camouflage: chromatophores change color/pattern
- Closed circulatory system (unique for mollusks)
- Intelligence examples:
  - Problem-solving (opening jars)
  - Tool use (carry coconut shells)
  - Learning (observe other octopuses)
  - Escape artistry (from tanks)

**Importance:**
- Food source: calamari, oysters, clams
- Pearls: luxury goods
- Ecological: water filtration, food chains
- Pest: some slugs/snails damage crops

